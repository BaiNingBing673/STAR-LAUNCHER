package com.star.launcher.bridge.config

import com.star.launcher.bridge.model.BridgeAuthMode
import com.star.launcher.bridge.model.BridgeTransportType
import com.star.launcher.bridge.model.GeyserConfig
import com.star.launcher.bridge.storage.BridgeStoragePaths
import java.io.File

data class ConfigValidationResult(
    val isValid: Boolean,
    val issues: List<String> = emptyList()
)

/**
 * Generates, updates, parses, and validates Geyser Standalone `config.yml`.
 * Never hardcodes unsupported transport assumptions; always inspects active config values.
 */
class GeyserConfigManager(
    private val paths: BridgeStoragePaths
) {
    fun validate(config: GeyserConfig): ConfigValidationResult {
        val issues = mutableListOf<String>()
        if (config.bedrockAddress.isBlank()) {
            issues += "Bedrock listen address cannot be blank"
        }
        if (config.bedrockPort !in 1024..65535) {
            issues += "Bedrock port ${config.bedrockPort} must be between 1024 and 65535 on unprivileged Android"
        }
        if (config.remoteAddress.isBlank()) {
            issues += "Java backend remote address cannot be blank"
        }
        if (config.remotePort !in 1..65535) {
            issues += "Java backend remote port ${config.remotePort} must be between 1 and 65535"
        }
        if (config.bedrockPort == config.remotePort && isLocalAddress(config.remoteAddress)) {
            issues += "Bedrock port (${config.bedrockPort}) cannot match local Java server port (${config.remotePort})"
        }
        if (config.authType == BridgeAuthMode.FLOODGATE && config.floodgateKeyFile.isBlank()) {
            issues += "Floodgate key filename cannot be blank when auth-type is floodgate"
        }
        if (config.memoryLimitMb < GeyserConfig.MIN_MEMORY_MB || config.memoryLimitMb > GeyserConfig.MAX_MEMORY_MB) {
            issues += "Geyser memory limit (${config.memoryLimitMb} MB) must be between ${GeyserConfig.MIN_MEMORY_MB} and ${GeyserConfig.MAX_MEMORY_MB} MB"
        }
        return ConfigValidationResult(issues.isEmpty(), issues)
    }

    fun writeConfig(config: GeyserConfig): File {
        val validation = validate(config)
        require(validation.isValid) {
            "Invalid Geyser configuration: ${validation.issues.joinToString("; ")}"
        }
        val file = paths.geyserConfigFile()
        file.parentFile?.mkdirs()
        val rendered = renderConfigYaml(config)
        val tmp = File(file.parentFile, "${file.name}.tmp")
        tmp.writeText(rendered, Charsets.UTF_8)
        if (!tmp.renameTo(file)) {
            tmp.copyTo(file, overwrite = true)
            tmp.delete()
        }
        return file
    }

    fun readActiveConfig(fallback: GeyserConfig = GeyserConfig()): GeyserConfig {
        val file = paths.geyserConfigFile()
        if (!file.isFile) return fallback
        return parseConfigYaml(file.readText(Charsets.UTF_8), fallback)
    }

    fun renderConfigYaml(config: GeyserConfig): String {
        val escapedMotd1 = yamlDoubleQuoted(config.motd1)
        val escapedMotd2 = yamlDoubleQuoted(config.motd2)
        val escapedServerName = yamlDoubleQuoted(config.serverName)
        val escapedFloodgateKey = yamlDoubleQuoted(config.floodgateKeyFile)
        val escapedBedrockAddr = yamlDoubleQuoted(config.bedrockAddress.trim())
        val escapedRemoteAddr = yamlDoubleQuoted(config.remoteAddress.trim())
        val debugFlag = if (config.debugMode) "true" else "false"

        return """
            |# Generated by STAR Launcher Bedrock Bridge
            |# Do not edit sensitive keys manually if managed by STAR FloodgateManager.
            |bedrock:
            |  address: $escapedBedrockAddr
            |  port: ${config.bedrockPort}
            |  clone-remote-port: false
            |  motd1: $escapedMotd1
            |  motd2: $escapedMotd2
            |  server-name: $escapedServerName
            |  compression-level: 6
            |  enable-proxy-protocol: false
            |
            |remote:
            |  address: $escapedRemoteAddr
            |  port: ${config.remotePort}
            |  auth-type: ${config.authType.configValue}
            |  allow-password-authentication: true
            |  use-proxy-protocol: false
            |  forward-hostname: false
            |
            |floodgate-key-file: $escapedFloodgateKey
            |
            |# Transport metadata recorded by STAR Bridge (Geyser Standalone uses UDP + TCP on bedrock.port)
            |star-transport: ${config.transport.configValue}
            |
            |command-suggestions: true
            |passthrough-motd: false
            |passthrough-protocol-name: false
            |passthrough-player-counts: true
            |legacy-ping-passthrough: false
            |ping-passthrough-interval: 3
            |max-players: 100
            |debug-mode: $debugFlag
            |allow-third-party-capes: true
            |show-cooldown: title
            |show-coordinates: true
            |disable-bedrock-scaffolding: false
            |emote-offhand-workaround: disabled
            |config-version: 4
            |""".trimMargin()
    }

    fun parseConfigYaml(rawYaml: String, fallback: GeyserConfig = GeyserConfig()): GeyserConfig {
        var currentSection = ""
        var bedrockAddress = fallback.bedrockAddress
        var bedrockPort = fallback.bedrockPort
        var motd1 = fallback.motd1
        var motd2 = fallback.motd2
        var serverName = fallback.serverName
        var remoteAddress = fallback.remoteAddress
        var remotePort = fallback.remotePort
        var authType = fallback.authType
        var floodgateKeyFile = fallback.floodgateKeyFile
        var transport = fallback.transport
        var debugMode = fallback.debugMode

        rawYaml.lineSequence().forEach { rawLine ->
            val withoutComment = stripYamlComment(rawLine)
            if (withoutComment.isBlank()) return@forEach
            val indent = withoutComment.takeWhile { it == ' ' }.length
            val trimmed = withoutComment.trim()
            val colonIdx = trimmed.indexOf(':')
            if (colonIdx <= 0) return@forEach

            val key = trimmed.substring(0, colonIdx).trim()
            val valuePart = unquoteYaml(trimmed.substring(colonIdx + 1).trim())

            if (indent == 0 && valuePart.isEmpty()) {
                currentSection = key
                return@forEach
            } else if (indent == 0) {
                currentSection = ""
            }

            when ("$currentSection.$key") {
                "bedrock.address" -> if (valuePart.isNotBlank()) bedrockAddress = valuePart
                "bedrock.port" -> valuePart.toIntOrNull()?.let { bedrockPort = it }
                "bedrock.motd1" -> motd1 = valuePart
                "bedrock.motd2" -> motd2 = valuePart
                "bedrock.server-name" -> if (valuePart.isNotBlank()) serverName = valuePart
                "remote.address", "java.address" -> if (valuePart.isNotBlank()) remoteAddress = valuePart
                "remote.port", "java.port" -> valuePart.toIntOrNull()?.let { remotePort = it }
                "remote.auth-type", "java.auth-type", ".auth-type" -> {
                    BridgeAuthMode.values().firstOrNull { it.configValue.equals(valuePart, ignoreCase = true) }
                        ?.let { authType = it }
                }
                "bedrock.transport", ".star-transport", ".transport" -> {
                    BridgeTransportType.values().firstOrNull { it.configValue.equals(valuePart, ignoreCase = true) }
                        ?.let { transport = it }
                }
                ".floodgate-key-file" -> if (valuePart.isNotBlank()) floodgateKeyFile = valuePart
                ".debug-mode" -> valuePart.toBooleanStrictOrNull()?.let { debugMode = it }
            }
        }

        return fallback.copy(
            bedrockAddress = bedrockAddress,
            bedrockPort = bedrockPort,
            motd1 = motd1,
            motd2 = motd2,
            serverName = serverName,
            remoteAddress = remoteAddress,
            remotePort = remotePort,
            authType = authType,
            floodgateKeyFile = floodgateKeyFile,
            transport = transport,
            debugMode = debugMode
        )
    }

    private fun stripYamlComment(line: String): String {
        var inSingle = false
        var inDouble = false
        for (i in line.indices) {
            val ch = line[i]
            when {
                ch == '\'' && !inDouble -> inSingle = !inSingle
                ch == '"' && !inSingle && (i == 0 || line[i - 1] != '\\') -> inDouble = !inDouble
                ch == '#' && !inSingle && !inDouble -> return line.substring(0, i)
            }
        }
        return line
    }

    private fun unquoteYaml(raw: String): String {
        if (raw.length >= 2 && ((raw.startsWith('"') && raw.endsWith('"')) || (raw.startsWith('\'') && raw.endsWith('\'')))) {
            return raw.substring(1, raw.length - 1).replace("\\\"", "\"").replace("\\\\", "\\")
        }
        return raw
    }

    private fun yamlDoubleQuoted(raw: String): String {
        val clean = raw.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", " ").replace("\r", "")
        return "\"$clean\""
    }

    private fun isLocalAddress(addr: String): Boolean {
        val norm = addr.trim().lowercase()
        return norm == "127.0.0.1" || norm == "localhost" || norm == "0.0.0.0" || norm == "::1" || norm == "auto"
    }
}
